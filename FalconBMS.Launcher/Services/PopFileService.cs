    private readonly CallsignService _callsign = new();

    public void SavePop(string baseDir, string installKeyName)
    {
        string pilotCallsign = _callsign.ReadPilotCallsign(installKeyName);
        string configDir = Path.Combine(baseDir, "User", "Config");
        string backupDir = Path.Combine(configDir, "Backup");
        string filename = Path.Combine(configDir, pilotCallsign + ".pop");
        string backupName = Path.Combine(backupDir, pilotCallsign + ".pop");

        Directory.CreateDirectory(configDir);
        Directory.CreateDirectory(backupDir);

        if (!File.Exists(filename))
            File.WriteAllBytes(filename, CreateFreshPopTemplate437());

        if (!File.Exists(backupName))
            File.Copy(filename, backupName, true);

        File.SetAttributes(filename, File.GetAttributes(filename) & ~FileAttributes.ReadOnly);

        byte[] bs = File.ReadAllBytes(filename);

        byte[] keyFileName = Encoding.ASCII.GetBytes("BMS - Auto");
        for (int i = 0; i <= 15; i++)
        {
            if (i >= keyFileName.Length)
            {
                bs[336 + i] = 0x00;
                continue;
            }

            bs[336 + i] = keyFileName[i];
        }

        // 4.37+ / 4.38 POP layout used by the original launcher:
        // 336 + 48 = TrackIR mode (0 = Head Forward, 1 = Zoom FOV)
        // 341 + 48 = External MouseLook
        // 342 + 48 = Natural Head Movement
        // 362 + 48 = Roll-linked NWS
        // 12       = Smart Scaling (0x01 off, 0x05 on)
        // 0 bit 6  = Pilot Model
        bs[336 + 48] = Properties.Settings.Default.Misc_TrackIRZ ? (byte)0x01 : (byte)0x00;
        bs[341 + 48] = Properties.Settings.Default.Misc_ExMouseLook ? (byte)0x01 : (byte)0x00;
        bs[342 + 48] = Properties.Settings.Default.Misc_NaturalHeadMovement ? (byte)0x01 : (byte)0x00;
        bs[362 + 48] = Properties.Settings.Default.Misc_RLNWS ? (byte)0x01 : (byte)0x00;

        bs[12] = Properties.Settings.Default.Misc_SmartScalingOverride ? (byte)0x05 : (byte)0x01;

        // Pilot Model is stored as bit #6 in byte 0 on the 4.37+ layout.
        // Keep the original launcher's masking so we do not mess up the other expected bits.
        bs[0] &= 0b01110011;
        bs[0] |= 0b00010011;

        if (Properties.Settings.Default.Misc_PilotModel)
            bs[0] |= 0b00100000;
        else
            bs[0] &= 0b11011111;

        File.WriteAllBytes(filename, bs);
    }

