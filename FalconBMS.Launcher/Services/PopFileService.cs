/// <summary>
/// Creates or updates the .pop file used by the launcher workflow before launch.
/// For now this writes the 4.38 specific view settings directly into the POP bytes,
/// matching the original launcher's 4.37+ storage layout.
/// </summary>
public sealed class PopFileService
